import type { AggregateSkuRow } from "./order-export";
import { openPrintDocument } from "./print-html";

/**
 * Single-page "Prep List": aggregated quantities, no decorations.
 * One row per product showing how much to prepare today, summed across orders.
 *
 * Columns: Product | Total kg | Total pcs | # Orders | Line Total
 *
 * Opens a print-ready window with proper Bengali shaping via the OS font
 * shaper. The user picks "Save as PDF" in the print dialog.
 */
export function downloadPrepListPDF(rows: AggregateSkuRow[], brandLabel = "Bazarey Meat Delivery"): void {
  const totalsKg = rows.reduce((s, r) => s + r.totalKg, 0);
  const totalsPcs = rows.reduce((s, r) => s + r.totalPcs, 0);
  const stamp = new Date().toLocaleString("en-GB", {
    year: "numeric", month: "short", day: "2-digit",
    hour: "2-digit", minute: "2-digit",
  });
  const brandInitials = brandLabel
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((w) => w[0]!.toUpperCase())
    .join("");

  const body = rows.length === 0
    ? `<div class="empty">No orders in selected range.</div>`
    : `<table class="report">
        <thead>
          <tr>
            <th style="width:48px;">#</th>
            <th>Product</th>
            <th class="num" style="width:110px;">Total kg</th>
            <th class="num" style="width:110px;">Total pcs</th>
            <th class="num" style="width:100px;"># Orders</th>
          </tr>
        </thead>
        <tbody>
          ${rows.map((r, i) => {
            const name = (r.productNameBn || r.productName || "").trim();
            return `<tr>
              <td style="color:#888;">${i + 1}</td>
              <td><strong>${escape(name)}</strong></td>
              <td class="num">${r.totalKg ? fmtQty(r.totalKg, "kg") : "—"}</td>
              <td class="num">${r.totalPcs ? fmtQty(r.totalPcs, "pcs") : "—"}</td>
              <td class="num">${r.orderCount}</td>
            </tr>`;
          }).join("")}
        </tbody>
        <tfoot>
          <tr>
            <td colspan="2">Totals</td>
            <td class="num">${fmtQty(totalsKg, "kg")}</td>
            <td class="num">${fmtQty(totalsPcs, "pcs")}</td>
            <td class="num">${rows.reduce((s, r) => s + r.orderCount, 0)}</td>
          </tr>
        </tfoot>
      </table>`;

  openPrintDocument({
    title: `Prep List — ${stamp}`,
    pageSize: "A4",
    bodyHtml: `
      <div class="report-shell">
        <div class="brand-bar">
          <div class="brand-mark">${escape(brandInitials)}</div>
          <div>
            <div class="brand-name">${escape(brandLabel)}</div>
            <div class="brand-tag">Daily preparation summary</div>
          </div>
        </div>
        <div class="meta">
          <div>
            <h1>Prep List</h1>
            <div class="sub">${rows.length} product${rows.length === 1 ? "" : "s"} across all selected orders</div>
          </div>
          <div class="stamp">${escape(stamp)}</div>
        </div>
        ${body}
        <div class="footer-note">Generated by Bazarey Ops · ${escape(brandLabel)}</div>
      </div>
    `,
  });
}

function fmtQty(n: number, unit: string): string {
  if (unit === "kg") {
    const rounded = Math.round(n * 100) / 100;
    return (Number.isInteger(rounded) ? rounded.toString() : rounded.toFixed(2).replace(/\.?0+$/, "")) + " kg";
  }
  return Math.round(n).toString() + " pcs";
}

function escape(s: string): string {
  return s.replace(/[&<>"']/g, (c) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;",
    "'": "&#39;",
  }[c]!));
}